class UuidType(TypeDecorator):
    """UUID column that works on PostgreSQL and on SQLite.

    PostgreSQL gets a native ``uuid``; everything else stores the canonical
    36-character text form. Values come back as :class:`uuid.UUID` either way, so
    application code never has to care which database it is talking to.
    """

    impl = String(36)
    cache_ok = True

    def load_dialect_impl(self, dialect):
        if dialect.name == "postgresql":
            return dialect.type_descriptor(PgUUID(as_uuid=True))
        return dialect.type_descriptor(String(36))

    def process_bind_param(self, value, dialect):
        if value is None:
            return None
        parsed = value if isinstance(value, UUID) else UUID(str(value))
        return parsed if dialect.name == "postgresql" else str(parsed)

    def process_result_value(self, value, dialect):
        if value is None:
            return None
        return value if isinstance(value, UUID) else UUID(str(value))


_JSONB = JSONB().with_variant(JSON(), "sqlite")
_UUID = UuidType()
_ARRAY_TEXT = ARRAY(Text()).with_variant(JSON(), "sqlite")


def _timestamps(table_name: str) -> list[Column]:
    return [
        Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
        Column("created_by", _UUID, nullable=True),
        Column("updated_at", DateTime(timezone=True), nullable=True),
        Column("updated_by", _UUID, nullable=True),
    ]


