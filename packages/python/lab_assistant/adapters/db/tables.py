def embedding_table_for(dimensions: int) -> Table:
    """Return (defining if needed) the projection table for ``dimensions``.

    Vectors of different dimensions never share a column, and an embedding column
    never lands on a domain row.
    """
    if dimensions in _EMBEDDING_TABLES:
        return _EMBEDDING_TABLES[dimensions]
    try:
        from pgvector.sqlalchemy import Vector

        vector_type: Any = Vector(dimensions)
    except ModuleNotFoundError:
        # Without pgvector installed the column is declared as an array so the
        # schema still validates; the migration installs the extension and casts.
        vector_type = ARRAY(Float()).with_variant(JSON(), "sqlite")
    table = Table(
        f"chunk_embeddings_{dimensions}",
        METADATA,
        Column("chunk_key", Text, primary_key=True),
        Column(
            "workspace_id", _UUID, ForeignKey("workspaces.id", ondelete="CASCADE"), nullable=False
        ),
        Column(
            "release_id",
            _UUID,
            ForeignKey("corpus_releases.id", ondelete="CASCADE"),
            primary_key=True,
        ),
        Column("work_id", _UUID, nullable=False),
        Column("profile_id", Text, primary_key=True),
        Column("vector", vector_type, nullable=False),
        Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
        Index(
            f"ix_chunk_embeddings_{dimensions}_release",
            "workspace_id",
            "release_id",
            "profile_id",
        ),
        extend_existing=True,
    )
    _EMBEDDING_TABLES[dimensions] = table
    return table


