"""PostgreSQL schema.

Design rules, all of them load-bearing:

* **``workspace_id`` on every domain table**, with foreign keys and indexes. This
  is the irreversible half of tenancy-readiness: the column and the repository
  signature are cheap now and a rewrite later.
* **Queryable fields are real columns.** Identity, status, lifecycle, digests,
  policy references, and anything a constraint or a filter touches. A ``payload``
  JSONB column carries only source-specific extras and versioned sub-documents —
  never identity, policy, lifecycle state, or evidence links.
* **One active work per strong identifier**, enforced by a partial unique index
  rather than by application discipline.
* **Vectors of different dimensions never share a column.** Embedding projections
  live in per-dimension tables created by the projection registry.
* **Published releases are immutable**, and the active alias must point at a
  published release — checked by constraint and by the integrity job.

SQLAlchemy Core is used rather than the ORM: rows are mapped explicitly, so no
lazy relationship can load inside an async request and no ``selectinload`` is
needed to avoid it.
"""

